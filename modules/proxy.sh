#!/usr/bin/env bash
# Module: Reverse proxy — HAProxy only (PasarGuard single-port)
# shellcheck shell=bash
# shellcheck disable=SC2034  # PROXY_* settings are saved indirectly via ${!k}

PROXY_STATE_DIR="${PROXY_STATE_DIR:-${PGCTB_STATE_DIR}/proxy}"
PROXY_CONFIG_FILE="${PROXY_CONFIG_FILE:-${PROXY_STATE_DIR}/config.env}"
PROXY_HAPROXY_CERT_DIR="${PROXY_HAPROXY_CERT_DIR:-/etc/haproxy/certs}"
PROXY_HAPROXY_CFG="${PROXY_HAPROXY_CFG:-/etc/haproxy/haproxy.cfg}"
PROXY_HAPROXY_CFG_BAK="${PROXY_HAPROXY_CFG_BAK:-${PROXY_STATE_DIR}/haproxy.cfg.pre-mrclock}"
PROXY_BIND_IPV6="${PROXY_BIND_IPV6:-auto}"  # auto | yes | no
PROXY_PANEL_APP_DIR="${PROXY_PANEL_APP_DIR:-${SSL_PANEL_APP_DIR:-/opt/pasarguard}}"
PROXY_PANEL_ENV_SNAPSHOT="${PROXY_PANEL_ENV_SNAPSHOT:-${PROXY_STATE_DIR}/panel.env.pre-haproxy}"
PROXY_VERIFY_TRIES="${PROXY_VERIFY_TRIES:-20}"
PROXY_HAPROXY_CFG_LAST="${PROXY_HAPROXY_CFG_LAST:-${PROXY_STATE_DIR}/haproxy.cfg.last}"

# --- helpers ---------------------------------------------------------------

_proxy_ensure_state() {
  mkdir -p "$PROXY_STATE_DIR" "$PROXY_HAPROXY_CERT_DIR"
  chmod 700 "$PROXY_STATE_DIR" 2>/dev/null || true
}

PROXY_CONFIG_KEYS=(
  PROXY_ENGINE PROXY_MODE PROXY_PANEL_DOMAIN PROXY_SUB_DOMAIN
  PROXY_BACKEND_HOST PROXY_BACKEND_PORT PROXY_LISTEN_HTTPS PROXY_LISTEN_HTTP
  PROXY_EXTRA_PORTS PROXY_EXTRA_PLAIN_PORTS
  PROXY_REALITY_SNI PROXY_REALITY_BACKEND PROXY_FALLBACK_BACKEND PROXY_ACME_PORT
)

_proxy_save_config() {
  _proxy_ensure_state
  local k tmp
  tmp="$(mktemp "${PROXY_STATE_DIR}/.config.XXXXXX")"
  {
    printf '# Generated by PGClockTB (parsed, never sourced)\n'
    for k in "${PROXY_CONFIG_KEYS[@]}"; do
      kv_line "$k" "${!k-}"
    done
  } >"$tmp"
  chmod 600 "$tmp"
  mv -f "$tmp" "$PROXY_CONFIG_FILE"
}

_proxy_load_config() {
  PROXY_ENGINE=""
  PROXY_MODE=""
  PROXY_PANEL_DOMAIN=""
  PROXY_SUB_DOMAIN=""
  PROXY_BACKEND_HOST="127.0.0.1"
  PROXY_BACKEND_PORT="8000"
  PROXY_LISTEN_HTTPS="443"
  PROXY_LISTEN_HTTP="80"
  PROXY_EXTRA_PORTS=""
  PROXY_EXTRA_PLAIN_PORTS=""
  PROXY_REALITY_SNI=""
  PROXY_REALITY_BACKEND="127.0.0.1:12000"
  PROXY_FALLBACK_BACKEND="127.0.0.1:11000"
  PROXY_ACME_PORT="18080"
  kv_load_file "$PROXY_CONFIG_FILE" "${PROXY_CONFIG_KEYS[@]}"
}

_proxy_valid_domain() {
  local d="$1"
  [[ "$d" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]
}

_proxy_valid_host() {
  # IPv4, localhost, or simple hostname/FQDN (no spaces / shell metacharacters)
  local h="$1"
  [[ -n "$h" ]] || return 1
  if declare -F is_ipv4 >/dev/null 2>&1 && is_ipv4 "$h"; then
    return 0
  fi
  [[ "$h" == "localhost" || "$h" == "::1" ]] && return 0
  [[ "$h" =~ ^[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$ ]]
}

_proxy_clean_ports() {
  # _proxy_clean_ports RAW EXCLUDE... → valid, deduped ports not in EXCLUDE
  local raw="$1"
  shift
  local p out="" bad="" ex
  local -a parts=()
  read -r -a parts <<<"${raw//,/ }"
  for p in "${parts[@]}"; do
    if [[ -z "$(normalize_port_list "$p")" ]]; then
      bad+="${bad:+ }$p"
      continue
    fi
    for ex in "$@"; do
      [[ "$p" == "$ex" ]] && continue 2
    done
    [[ " $out " == *" $p "* ]] && continue
    out+="${out:+ }$p"
  done
  [[ -n "$bad" ]] && ui_warn "Ignoring invalid ports: ${bad}" >&2
  printf '%s\n' "$out"
}

_proxy_valid_hostport() {
  local hp="$1" host port
  [[ "$hp" == *:* ]] || return 1
  host="${hp%:*}"
  port="${hp##*:}"
  _proxy_valid_host "$host" && is_port "$port"
}

_proxy_cert_covers() {
  # _proxy_cert_covers CERT DOMAIN → 0 if the certificate is valid for DOMAIN
  local cert="$1" domain="$2" out
  [[ -s "$cert" ]] || return 1
  have_cmd openssl || return 2
  out="$(openssl x509 -in "$cert" -noout -checkhost "$domain" 2>/dev/null || true)"
  [[ "$out" == *" does match certificate"* ]]
}

_proxy_key_matches() {
  # _proxy_key_matches CERT KEY → 0 if KEY is the private key of CERT
  local cert="$1" key="$2" a b
  [[ -s "$key" ]] || return 1
  have_cmd openssl || return 0
  a="$(openssl x509 -in "$cert" -noout -pubkey 2>/dev/null)" || return 1
  b="$(openssl pkey -in "$key" -pubout 2>/dev/null)" || return 1
  [[ -n "$a" && "$a" == "$b" ]]
}

_proxy_ssl_domains() {
  # Space-separated domains of the PGClockTB SSL certificate (from SSL config)
  local SSL_DOMAINS="" SSL_PRIMARY=""
  kv_load_file "${SSL_CONFIG_FILE:-${PGCTB_STATE_DIR}/ssl/config.env}" SSL_DOMAINS SSL_PRIMARY
  printf '%s\n' "${SSL_DOMAINS:-$SSL_PRIMARY}"
}

_proxy_sync_pem_from_ssl() {
  # Build <cert dir>/<domain>.pem from a certificate that really covers <domain>:
  # PGClockTB SSL live copy → PasarGuard panel cert → Let's Encrypt live dir.
  local domain="$1"
  [[ -n "$domain" ]] || return 1
  _proxy_ensure_state

  local ssl_live="${PGCTB_STATE_DIR}/ssl/live"
  local panel_dir="${SSL_PANEL_CERT_DIR:-/var/lib/pasarguard/certs}"
  local -a pairs=(
    "${ssl_live}/fullchain.cer|${ssl_live}/key.pem|live"
    "${panel_dir}/${domain}/fullchain.pem|${panel_dir}/${domain}/privkey.pem|named"
    "${panel_dir}/${domain}.cer|${panel_dir}/${domain}.cer.key|named"
    "/etc/letsencrypt/live/${domain}/fullchain.pem|/etc/letsencrypt/live/${domain}/privkey.pem|named"
  )
  local pair cert key kind rc out tmp
  for pair in "${pairs[@]}"; do
    IFS='|' read -r cert key kind <<<"$pair"
    [[ -s "$cert" && -s "$key" ]] || continue
    rc=0
    _proxy_cert_covers "$cert" "$domain" || rc=$?
    if (( rc == 2 )); then
      # No openssl: trust per-domain paths by name; the shared live copy only
      # when the PGClockTB SSL config lists this domain.
      if [[ "$kind" == "live" && " $(_proxy_ssl_domains) " != *" ${domain} "* ]]; then
        continue
      fi
    elif (( rc != 0 )); then
      continue
    fi
    _proxy_key_matches "$cert" "$key" || continue
    out="${PROXY_HAPROXY_CERT_DIR}/${domain}.pem"
    tmp="$(mktemp "${PROXY_HAPROXY_CERT_DIR}/.pem.XXXXXX")"
    chmod 600 "$tmp"
    cat "$cert" "$key" >"$tmp"
    mv -f "$tmp" "$out"
    return 0
  done
  return 1
}

_proxy_ensure_certs_for_domains() {
  # Every requested domain must get a matching PEM — partial success is failure.
  local d
  local -a missing=()
  for d in "$@"; do
    [[ -n "$d" ]] || continue
    if _proxy_sync_pem_from_ssl "$d"; then
      ui_success "HAProxy PEM ready: ${PROXY_HAPROXY_CERT_DIR}/${d}.pem"
    else
      ui_warn "No certificate covering ${d} was found"
      missing+=("$d")
    fi
  done
  if ((${#missing[@]} > 0)); then
    ui_error "Missing certificates for: ${missing[*]}"
    ui_info "Issue one certificate for all of them: SSL Certificates → Issue / Setup"
    return 1
  fi
  return 0
}

_proxy_backup_file() {
  local src="$1"
  local dest="$2"
  [[ -f "$src" ]] || return 0
  [[ -f "$dest" ]] && return 0
  mkdir -p "$(dirname "$dest")"
  cp -a "$src" "$dest"
  ui_info "Backed up ${src} → ${dest}"
}

_proxy_snapshot_cfg() {
  # pre-mrclock: original distro config (kept once, used by Remove).
  # last: config right before this write (used to roll back a bad write).
  _proxy_backup_file "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_BAK"
  mkdir -p "$(dirname "$PROXY_HAPROXY_CFG_LAST")"
  if [[ -f "$PROXY_HAPROXY_CFG" ]]; then
    cp -a "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_LAST"
  else
    rm -f "$PROXY_HAPROXY_CFG_LAST"
  fi
}

_proxy_bind() {
  # _proxy_bind PORT → dual-stack bind when the kernel has IPv6, else IPv4 only
  # (":::port" makes HAProxy refuse to start on hosts booted with ipv6.disable=1)
  local port="$1" v6="$PROXY_BIND_IPV6"
  if [[ "$v6" == "auto" ]]; then
    [[ -e /proc/net/if_inet6 ]] && v6=yes || v6=no
  fi
  if [[ "$v6" == "yes" ]]; then
    printf ':::%s v4v6\n' "$port"
  else
    printf '0.0.0.0:%s\n' "$port"
  fi
}

_proxy_print_panel_guide() {
  local backend_host="${1:-127.0.0.1}"
  local backend_port="${2:-8000}"
  ui_box_start "Panel settings (PasarGuard single-port docs)"
  ui_info "HAProxy terminates TLS. Panel must listen on local HTTP only."
  ui_kv "Panel Host" "$backend_host"
  ui_kv "Panel Port" "$backend_port"
  ui_info "Also set the same values in Panel UI → Settings → Panel"
  ui_info "Host ports for users: 443 / 80 / extra ports (HAProxy listens on them)"
  ui_box_end
}

# Align panel .env with official single-port guide: local HTTP, no Uvicorn TLS.
_proxy_prepare_panel_for_haproxy() {
  # Panel → local HTTP behind HAProxy. The .env as it was BEFORE the first
  # HAProxy setup is kept, so Remove can make the panel reachable again.
  local backend_host="${1:-127.0.0.1}"
  local backend_port="${2:-8000}"
  local envf="${PROXY_PANEL_APP_DIR}/.env"
  [[ -d "$PROXY_PANEL_APP_DIR" ]] || {
    ui_warn "${PROXY_PANEL_APP_DIR} not found — set Panel Host/Port in the UI manually"
    return 0
  }
  if [[ ! -f "$envf" ]]; then
    touch "$envf"
    chmod 600 "$envf"
  else
    backup_file "$envf" 2>/dev/null || true
    if [[ ! -f "$PROXY_PANEL_ENV_SNAPSHOT" ]]; then
      _proxy_ensure_state
      cp -a "$envf" "$PROXY_PANEL_ENV_SNAPSHOT"
    fi
  fi

  local k
  for k in UVICORN_SSL_CERTFILE UVICORN_SSL_KEYFILE UVICORN_SSL_CA_TYPE UVICORN_UDS; do
    _ssl_env_comment_key "$envf" "$k"
  done
  _ssl_env_upsert "$envf" "UVICORN_HOST" "$backend_host" spaced
  _ssl_env_upsert "$envf" "UVICORN_PORT" "$backend_port" bare
  ui_success "Panel .env prepared for HAProxy (local HTTP ${backend_host}:${backend_port}, SSL keys commented)"
  _ssl_restart_compose "$PROXY_PANEL_APP_DIR" "PasarGuard panel"
}

_proxy_detect_panel_port() {
  # Current panel port from .env (default 8000)
  local p
  p="$(_ssl_env_get "${PROXY_PANEL_APP_DIR}/.env" UVICORN_PORT 2>/dev/null || true)"
  is_port "${p:-}" && printf '%s\n' "$p" || printf '8000\n'
}

_proxy_port_owner() {
  # Process name listening on TCP PORT ("" = free)
  local port="$1"
  have_cmd ss || return 0
  ss -tlnpH "sport = :${port}" 2>/dev/null \
    | sed -n 's/.*users:(("\([^"]*\)".*/\1/p' | head -n1
}

_proxy_check_port_conflicts() {
  # _proxy_check_port_conflicts PANEL_PORT_NOW PORT... → 1 when a port HAProxy
  # needs is held by something else (the panel itself is moving away: allowed)
  local panel_now="$1" p owner bad=0
  shift
  for p in "$@"; do
    [[ -n "$p" ]] || continue
    owner="$(_proxy_port_owner "$p")"
    [[ -z "$owner" || "$owner" == haproxy ]] && continue
    if [[ "$p" == "$panel_now" ]]; then
      ui_info "Port ${p} is the panel's current port — the panel moves behind HAProxy"
      continue
    fi
    ui_error "Port ${p} is already used by '${owner}' — HAProxy cannot listen there"
    bad=1
  done
  if (( bad )); then
    ui_info "Move that service (e.g. an Xray inbound on 443 → use Node mode / another port) and retry"
    return 1
  fi
  return 0
}

_proxy_verify_through() {
  # Through HAProxy: panel domain must answer (not 403/5xx), unknown Host must get 403
  local domain="$1" port="$2" code wrong i
  have_cmd curl || return 2
  for ((i = 0; i < PROXY_VERIFY_TRIES; i++)); do
    code="$(curl -sk -o /dev/null --max-time 8 -w '%{http_code}' \
      --resolve "${domain}:${port}:127.0.0.1" "https://${domain}:${port}/" 2>/dev/null || true)"
    if [[ "$code" =~ ^[1-4][0-9][0-9]$ && "$code" != 403 ]]; then
      wrong="$(curl -sk -o /dev/null --max-time 8 -w '%{http_code}' \
        --resolve "pgclocktb-check.invalid:${port}:127.0.0.1" \
        "https://pgclocktb-check.invalid:${port}/" 2>/dev/null || true)"
      if [[ "$wrong" == 403 ]]; then
        ui_success "Verified via HAProxy: ${domain}:${port} → panel (HTTP ${code}); unknown host → 403"
        return 0
      fi
      ui_error "Unknown Host got HTTP ${wrong:-none} instead of 403"
      return 1
    fi
    sleep 2
  done
  ui_error "Panel not reachable through HAProxy on ${domain}:${port} (last HTTP ${code:-none})"
  return 1
}
