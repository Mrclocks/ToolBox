_proxy_warn_conflicts() {
  local other
  for other in caddy nginx; do
    if systemctl is-active --quiet "$other" 2>/dev/null; then
      ui_warn "${other} is active on this host — may conflict with HAProxy on :443"
      if have_tty && ui_confirm "Stop ${other} before continuing?" "Y"; then
        systemctl stop "$other" >/dev/null 2>&1 || true
        ui_info "Stopped ${other}"
      fi
    fi
  done
}

_proxy_install_haproxy() {
  if have_cmd haproxy; then
    ui_info "HAProxy already installed: $(haproxy -v 2>&1 | head -n1)"
    return 0
  fi
  ui_info "Installing HAProxy..."
  if ! apt_install_safe haproxy; then
    ui_error "Failed to install haproxy"
    return 1
  fi
  return 0
}

_proxy_write_haproxy_panel_cfg() {
  # Aligned with https://docs.pasarguard.org/en/learn/single-port/
  # listen front · mode http · Host ACL · deny default · PEM dir crt
  local panel_domain="$1"
  local sub_domain="$2"
  local backend_host="$3"
  local backend_port="$4"
  local listen_https="$5"
  local listen_http="$6"
  local extra_ssl_ports="$7"
  local extra_plain_ports="${8:-}"
  local p

  _proxy_snapshot_cfg

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# PGClockTB — PasarGuard panel single-port (HTTP mode)
# Based on official docs: https://docs.pasarguard.org/en/learn/single-port/
# Managed — regenerate from: pgclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode http
    log global
    option httplog
    option dontlognull
    timeout connect 5s
    timeout client  50s
    timeout server  50s
    maxconn 50000

# Official pattern: one listen block, several binds (SSL + plain HTTP).
# Port ${listen_http} stays plain HTTP (no forced redirect) so old HTTP
# subscription links keep working — same as PasarGuard docs.
listen front
    mode http
    option httplog
    log /dev/log local0
    bind $(_proxy_bind "$listen_https") ssl crt ${PROXY_HAPROXY_CERT_DIR}/
    bind $(_proxy_bind "$listen_http")
EOF

  for p in $extra_ssl_ports; do
    [[ "$p" =~ ^[0-9]+$ ]] || continue
    (( p >= 1 && p <= 65535 )) || continue
    [[ "$p" == "$listen_https" || "$p" == "$listen_http" ]] && continue
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    bind $(_proxy_bind "$p") ssl crt ${PROXY_HAPROXY_CERT_DIR}/
EOF
  done

  for p in $extra_plain_ports; do
    [[ "$p" =~ ^[0-9]+$ ]] || continue
    (( p >= 1 && p <= 65535 )) || continue
    [[ "$p" == "$listen_https" || "$p" == "$listen_http" ]] && continue
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    bind $(_proxy_bind "$p")
EOF
  done

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    capture request header X-Forwarded-For len 15
    capture request header Host len 50
    log-format "%ci:%cp [%tr] %ft %b/%s %TR/%Tw/%Tc/%Tr/%Ta %ST %B %CC %CS %tsc %ac/%fc/%bc/%sc/%rc %sq/%bq %hr %hs %{+Q}r %U"
    # Host may carry :port on non-default ports (e.g. 8443) — compare name only
    acl host_panel hdr(host),field(1,:) -i ${panel_domain}
    # Let's Encrypt HTTP-01 goes to acme.sh on a local port — HAProxy is never
    # stopped for issue/renew (no downtime)
    acl acme_challenge path_beg /.well-known/acme-challenge/
    use_backend acme if acme_challenge
EOF
  if [[ -n "$sub_domain" && "$sub_domain" != "$panel_domain" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    acl host_sub hdr(host),field(1,:) -i ${sub_domain}
    use_backend panel if host_panel
    use_backend sub if host_sub
EOF
  else
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend panel if host_panel
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend deny_backend

backend panel
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    server srv1 ${backend_host}:${backend_port}

backend sub
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    acl is_sub path_beg /sub/
    http-request deny if !is_sub
    server srv1 ${backend_host}:${backend_port}

backend acme
    mode http
    server acme 127.0.0.1:${PROXY_ACME_PORT:-18080}

backend deny_backend
    mode http
    http-request deny deny_status 403
EOF
}

_proxy_write_haproxy_node_cfg() {
  # Aligned with official node TCP / REALITY example (send-proxy + inspect-delay)
  local listen_https="$1"
  local reality_sni="$2"
  local reality_backend="$3"
  local fallback_backend="$4"

  _proxy_snapshot_cfg

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# PGClockTB — PasarGuard node single-port (TCP / SNI mode)
# Based on official docs: https://docs.pasarguard.org/en/learn/single-port/
# Managed — regenerate from: pgclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode tcp
    log global
    option tcplog
    timeout connect 5s
    timeout client  1h
    timeout server  1h
    maxconn 50000

listen front_node
    mode tcp
    bind *:${listen_https}
    tcp-request inspect-delay 5s
    tcp-request content accept if { req_ssl_hello_type 1 }
EOF

  if [[ -n "$reality_sni" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend reality if { req.ssl_sni -m end ${reality_sni} }
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend fallback_node

backend fallback_node
    mode tcp
    server srv1 ${fallback_backend}

backend reality
    mode tcp
    server srv1 ${reality_backend} send-proxy
EOF
}

_proxy_haproxy_validate_and_start() {
  if ! haproxy -c -f "$PROXY_HAPROXY_CFG"; then
    ui_error "HAProxy config invalid — see above. Running service was not touched."
    if [[ -f "$PROXY_HAPROXY_CFG_LAST" ]]; then
      cp -a "$PROXY_HAPROXY_CFG_LAST" "$PROXY_HAPROXY_CFG"
      ui_warn "Restored previous haproxy.cfg"
    else
      local aside
      aside="${PROXY_HAPROXY_CFG}.invalid.$(date +%Y%m%d%H%M%S)"
      mv -f "$PROXY_HAPROXY_CFG" "$aside"
      ui_warn "No previous config to restore — moved invalid file to ${aside}"
    fi
    return 1
  fi
  systemctl enable haproxy >/dev/null 2>&1 || true
  if systemctl restart haproxy; then
    ui_success "HAProxy restarted"
  else
    ui_error "HAProxy failed to start — journalctl -u haproxy -n 40"
    return 1
  fi
  if systemctl is-active --quiet haproxy; then
    ui_success "HAProxy is active"
    return 0
  fi
  ui_error "HAProxy is not active"
  return 1
}

_proxy_setup_panel() {
  local panel_domain sub_domain backend_host backend_port listen_https listen_http
  local extra_ports extra_plain raw_ports panel_now ssl_domains d
  local -a ssl_list=()

  # --- auto-detect (answers become defaults; Enter accepts) ---
  ssl_domains="$(_proxy_ssl_domains)"
  read -r -a ssl_list <<<"$ssl_domains"
  local def_panel="${PROXY_PANEL_DOMAIN:-${ssl_list[0]:-}}" def_sub="${PROXY_SUB_DOMAIN:-}"
  if [[ -z "$def_sub" && ${#ssl_list[@]} -gt 1 ]]; then
    for d in "${ssl_list[@]:1}"; do
      [[ "$d" == \*.* ]] || { def_sub="$d"; break; }
    done
  fi
  panel_now="$(_proxy_detect_panel_port)"
  local def_backend="$panel_now"
  # Panel directly on a public web port → move it to 8000 behind HAProxy
  if [[ "$panel_now" == 443 || "$panel_now" == 80 ]]; then
    def_backend=8000
  fi
  [[ -n "$ssl_domains" ]] && ui_info "From SSL config: ${ssl_domains}"
  ui_info "Panel currently listens on port ${panel_now} (from ${PROXY_PANEL_APP_DIR}/.env)"

  while true; do
    ui_ask panel_domain "Panel domain" "$def_panel"
    panel_domain="$(trim "${panel_domain,,}")"
    _proxy_valid_domain "$panel_domain" && break
    ui_warn "Invalid domain."
  done
  ui_ask sub_domain "Subscription domain (optional, Enter to skip)" "$def_sub"
  sub_domain="$(trim "${sub_domain,,}")"
  if [[ -n "$sub_domain" ]] && ! _proxy_valid_domain "$sub_domain"; then
    ui_warn "Ignoring invalid sub domain."
    sub_domain=""
  fi
  backend_host=127.0.0.1
  ui_ask_port backend_port "Panel local port behind HAProxy" "$def_backend"
  ui_ask_port listen_https "HTTPS listen port" "${PROXY_LISTEN_HTTPS:-443}"
  ui_ask_port listen_http "HTTP listen port (plain, per docs — no redirect)" "${PROXY_LISTEN_HTTP:-80}"
  ui_ask raw_ports "Extra HTTPS ports (optional, space-separated, e.g. 8443)" "${PROXY_EXTRA_PORTS:-}"
  extra_ports="$(_proxy_clean_ports "$raw_ports" "$listen_https" "$listen_http")"
  ui_ask raw_ports "Extra plain HTTP ports (optional, e.g. 9000)" "${PROXY_EXTRA_PLAIN_PORTS:-}"
  # shellcheck disable=SC2086  # extra_ports is a validated digit list
  extra_plain="$(_proxy_clean_ports "$raw_ports" "$listen_https" "$listen_http" $extra_ports)"

  # --- preflight ---
  local p
  # shellcheck disable=SC2086
  for p in "$listen_https" "$listen_http" $extra_ports $extra_plain "${PROXY_ACME_PORT:-18080}"; do
    if [[ "$p" == "$backend_port" ]]; then
      ui_error "Panel local port ${backend_port} collides with a HAProxy/ACME port (${p})."
      return 1
    fi
  done
  # shellcheck disable=SC2086
  _proxy_check_port_conflicts "$panel_now" "$listen_https" "$listen_http" $extra_ports $extra_plain || return 1
  if [[ "$backend_port" != "$panel_now" && -n "$(_proxy_port_owner "$backend_port")" ]]; then
    ui_error "Port ${backend_port} is already in use by '$(_proxy_port_owner "$backend_port")'."
    return 1
  fi

  if ! ui_confirm "Install HAProxy for ${panel_domain}${sub_domain:+ + $sub_domain} (panel → ${backend_host}:${backend_port})?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi

  _proxy_warn_conflicts
  _proxy_install_haproxy || return 1

  local -a cert_domains=("$panel_domain")
  [[ -n "$sub_domain" ]] && cert_domains+=("$sub_domain")
  if ! _proxy_ensure_certs_for_domains "${cert_domains[@]}"; then
    ui_info "Tip: Main menu → SSL Certificates → Issue / Setup first"
    return 1
  fi

  # --- apply as one transaction: haproxy.cfg + panel .env + proxy state ---
  local was_active=0
  systemctl is-active --quiet haproxy 2>/dev/null && was_active=1
  safety_txn_begin "haproxy-panel" "$PROXY_HAPROXY_CFG" "${PROXY_PANEL_APP_DIR}/.env" "$PROXY_CONFIG_FILE" || return 1

  _proxy_write_haproxy_panel_cfg \
    "$panel_domain" "$sub_domain" "$backend_host" "$backend_port" \
    "$listen_https" "$listen_http" "$extra_ports" "$extra_plain"
  if ! _proxy_haproxy_validate_and_start; then
    _proxy_rollback_panel "$was_active"
    return 1
  fi
  _proxy_prepare_panel_for_haproxy "$backend_host" "$backend_port"

  PROXY_ENGINE=haproxy
  PROXY_MODE=panel
  PROXY_PANEL_DOMAIN="$panel_domain"
  PROXY_SUB_DOMAIN="$sub_domain"
  PROXY_BACKEND_HOST="$backend_host"
  PROXY_BACKEND_PORT="$backend_port"
  PROXY_LISTEN_HTTPS="$listen_https"
  PROXY_LISTEN_HTTP="$listen_http"
  PROXY_EXTRA_PORTS="$extra_ports"
  PROXY_EXTRA_PLAIN_PORTS="$extra_plain"
  PROXY_ACME_PORT="${PROXY_ACME_PORT:-18080}"
  _proxy_save_config

  local vr=0
  _proxy_verify_through "$panel_domain" "$listen_https" || vr=$?
  if (( vr == 1 )); then
    ui_error "Rolling back HAProxy setup (config, panel .env, state)"
    _proxy_rollback_panel "$was_active"
    return 1
  fi
  (( vr == 2 )) && ui_warn "curl missing — could not verify through HAProxy"
  safety_txn_commit

  # ACME renewals now go through HAProxy (no stop/start of HAProxy)
  if declare -F _ssl_acme_switch_http >/dev/null 2>&1; then
    _ssl_acme_switch_http haproxy "$PROXY_ACME_PORT" || true
  fi

  ui_success "HAProxy panel mode ready (docs-aligned listen front)"
  _proxy_print_panel_guide "$backend_host" "$backend_port"
  ui_info "Firewall tip: ufw allow ${listen_https}/tcp ; ufw allow ${listen_http}/tcp"
  [[ -n "$extra_ports" ]] && ui_info "Also allow extra HTTPS: ${extra_ports}"
  [[ -n "$extra_plain" ]] && ui_info "Also allow plain ports: ${extra_plain}"
  return 0
}

_proxy_rollback_panel() {
  local was_active="${1:-0}"
  [[ -n "$PGCTB_TXN" ]] && safety_txn_rollback
  if (( was_active )); then
    systemctl restart haproxy >/dev/null 2>&1 || ui_warn "Restart haproxy manually"
  else
    systemctl stop haproxy >/dev/null 2>&1 || true
  fi
  _ssl_restart_compose "$PROXY_PANEL_APP_DIR" "PasarGuard panel"
  ui_warn "Previous HAProxy config and panel .env restored"
}

proxy_setup_haproxy() {
  ui_step "Setup HAProxy"
  if is_dry_run; then
    ui_info "[dry-run] Would install and configure HAProxy"
    return 0
  fi
  _proxy_load_config  # previous answers become defaults

  local mode_choice mode panel_domain sub_domain backend_host backend_port
  local listen_https listen_http extra_ports reality_sni reality_backend fallback_backend

  if ! ui_menu mode_choice "HAProxy mode" \
      "Panel — single-port HTTPS (recommended)" \
      "Node — TCP SNI / REALITY"; then
    ui_info "Back."
    return 0
  fi
  case "$mode_choice" in
    1) mode=panel ;;
    2) mode=node ;;
    *) return 0 ;;
  esac

  if [[ "$mode" == "panel" ]]; then
    _proxy_setup_panel
    return $?
  fi

  # Node mode
  ui_ask_port listen_https "Listen port" "443"
  ui_ask reality_sni "REALITY SNI suffix to match (e.g. reality.com)" ""
  reality_sni="$(trim "${reality_sni,,}")"
  if [[ -n "$reality_sni" ]] && ! _proxy_valid_domain "$reality_sni"; then
    ui_warn "Ignoring invalid REALITY SNI."
    reality_sni=""
  fi
  while true; do
    ui_ask reality_backend "REALITY backend host:port" "127.0.0.1:12000"
    reality_backend="$(trim "$reality_backend")"
    if _proxy_valid_hostport "$reality_backend"; then break; fi
    ui_warn "Invalid host:port."
  done
  while true; do
    ui_ask fallback_backend "Fallback / TLS backend host:port" "127.0.0.1:11000"
    fallback_backend="$(trim "$fallback_backend")"
    if _proxy_valid_hostport "$fallback_backend"; then break; fi
    ui_warn "Invalid host:port."
  done

  if ! ui_confirm "Install HAProxy node TCP mode on :${listen_https}?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi
  _proxy_warn_conflicts
  if ! _proxy_install_haproxy; then return 1; fi

  _proxy_write_haproxy_node_cfg "$listen_https" "$reality_sni" "$reality_backend" "$fallback_backend"

  if ! _proxy_haproxy_validate_and_start; then return 1; fi

  PROXY_ENGINE=haproxy
  PROXY_MODE=node
  PROXY_LISTEN_HTTPS="$listen_https"
  PROXY_REALITY_SNI="$reality_sni"
  PROXY_REALITY_BACKEND="$reality_backend"
  PROXY_FALLBACK_BACKEND="$fallback_backend"
  _proxy_save_config

  ui_success "HAProxy node mode ready on :${listen_https}"
  ui_box_start "Node inbound tips"
  ui_info "Point REALITY inbound listen to ${reality_backend} (127.0.0.1) with acceptProxyProtocol=true"
  ui_info "Point fallback/TLS inbound to ${fallback_backend}"
  ui_info "SNI match: *.${reality_sni:-<none>}"
  ui_box_end
  return 0
}


# --- Status / Remove -------------------------------------------------------

proxy_status() {
  ui_step "HAProxy — Status"
  _proxy_load_config
  ui_box_start "Saved configuration"
  ui_kv "Engine" "${PROXY_ENGINE:-(none)}"
  ui_kv "Mode" "${PROXY_MODE:-(none)}"
  ui_kv "Panel domain" "${PROXY_PANEL_DOMAIN:-(none)}"
  ui_kv "Sub domain" "${PROXY_SUB_DOMAIN:-(none)}"
  ui_kv "Backend" "${PROXY_BACKEND_HOST:-}:${PROXY_BACKEND_PORT:-}"
  ui_kv "HTTPS port" "${PROXY_LISTEN_HTTPS:-}"
  ui_kv "Extra HTTPS" "${PROXY_EXTRA_PORTS:-(none)}"
  ui_kv "Extra plain HTTP" "${PROXY_EXTRA_PLAIN_PORTS:-(none)}"
  ui_kv "Config file" "$PROXY_CONFIG_FILE"
  ui_box_end

  if have_cmd haproxy || systemctl list-unit-files haproxy.service 2>/dev/null | grep -q haproxy; then
    if systemctl is-active --quiet haproxy 2>/dev/null; then
      ui_success "haproxy: active"
    else
      ui_info "haproxy: installed, not active"
    fi
  else
    ui_info "haproxy: not installed"
  fi

  if [[ -d "$PROXY_HAPROXY_CERT_DIR" ]]; then
    local n
    n="$(find "$PROXY_HAPROXY_CERT_DIR" -maxdepth 1 -type f -name '*.pem' 2>/dev/null | wc -l | tr -d ' ')"
    ui_kv "HAProxy PEMs" "${n} under ${PROXY_HAPROXY_CERT_DIR}"
  fi
}

proxy_remove() {
  ui_step "HAProxy — Remove"
  _proxy_load_config
  if ! ui_confirm "Stop HAProxy and restore previous config if backed up?" "N"; then
    ui_warn "Cancelled."
    return 0
  fi
  systemctl disable --now haproxy >/dev/null 2>&1 || true
  if [[ -f "$PROXY_HAPROXY_CFG_BAK" ]]; then
    cp -a "$PROXY_HAPROXY_CFG_BAK" "$PROXY_HAPROXY_CFG"
    ui_info "Restored ${PROXY_HAPROXY_CFG}"
  fi
  # The panel was moved to local HTTP for HAProxy — give it back its own
  # listener, or it is unreachable once HAProxy is gone.
  if [[ "$PROXY_MODE" == "panel" ]]; then
    if [[ -f "$PROXY_PANEL_ENV_SNAPSHOT" && -d "$PROXY_PANEL_APP_DIR" ]]; then
      backup_file "${PROXY_PANEL_APP_DIR}/.env" 2>/dev/null || true
      cp -a "$PROXY_PANEL_ENV_SNAPSHOT" "${PROXY_PANEL_APP_DIR}/.env"
      rm -f "$PROXY_PANEL_ENV_SNAPSHOT"
      _ssl_restart_compose "$PROXY_PANEL_APP_DIR" "PasarGuard panel"
      ui_success "Panel .env restored to its pre-HAProxy state"
    else
      ui_warn "Panel still listens on local HTTP only — use SSL → Show .env → re-apply to serve TLS directly"
    fi
    if declare -F _ssl_acme_switch_http >/dev/null 2>&1; then
      _ssl_acme_switch_http standalone || true
    fi
  fi
  if [[ -f "$PROXY_CONFIG_FILE" ]]; then
    mv -f "$PROXY_CONFIG_FILE" "${PROXY_CONFIG_FILE}.removed.$(date +%Y%m%d%H%M%S)"
  fi
  ui_success "HAProxy stopped. Certificate PEM files were left in place."
}

proxy_status_remove_menu() {
  while true; do
    ui_clear
    ui_banner
    ui_menu_title "HAProxy — Status / Remove"
    printf '  %s 1)%s Status\n' "$C_ORANGE" "$C_RESET"
    printf '  %s 2)%s Remove / Stop\n' "$C_ORANGE" "$C_RESET"
    ui_menu_back_line
    local choice
    printf '%sSelect%s [0-2]: ' "$C_ORANGE" "$C_RESET"
    ui_read choice
    choice="$(trim "${choice:-}")"
    case "$choice" in
      1) ui_clear; proxy_status; ui_pause ;;
      2) ui_clear; proxy_remove; ui_pause ;;
      0|b|B|back|Back) return 0 ;;
      *) ui_warn "Invalid selection."; sleep 1 ;;
    esac
  done
}

