#!/usr/bin/env bash
# Module: Reverse proxy — HAProxy only (PasarGuard single-port)
# shellcheck shell=bash

PROXY_STATE_DIR="${PROXY_STATE_DIR:-${SECUREBOX_STATE_DIR}/proxy}"
PROXY_CONFIG_FILE="${PROXY_CONFIG_FILE:-${PROXY_STATE_DIR}/config.env}"
PROXY_HAPROXY_CERT_DIR="${PROXY_HAPROXY_CERT_DIR:-/etc/haproxy/certs}"
PROXY_HAPROXY_CFG="${PROXY_HAPROXY_CFG:-/etc/haproxy/haproxy.cfg}"
PROXY_HAPROXY_CFG_BAK="${PROXY_STATE_DIR}/haproxy.cfg.pre-mrclock"

# --- helpers ---------------------------------------------------------------

_proxy_ensure_state() {
  mkdir -p "$PROXY_STATE_DIR" "$PROXY_HAPROXY_CERT_DIR"
  chmod 700 "$PROXY_STATE_DIR" 2>/dev/null || true
}

_proxy_save_config() {
  _proxy_ensure_state
  cat >"$PROXY_CONFIG_FILE" <<EOF
# Generated by MrClock ToolBox
PROXY_ENGINE=${PROXY_ENGINE:-}
PROXY_MODE=${PROXY_MODE:-}
PROXY_PANEL_DOMAIN=${PROXY_PANEL_DOMAIN:-}
PROXY_SUB_DOMAIN=${PROXY_SUB_DOMAIN:-}
PROXY_BACKEND_HOST=${PROXY_BACKEND_HOST:-127.0.0.1}
PROXY_BACKEND_PORT=${PROXY_BACKEND_PORT:-8000}
PROXY_LISTEN_HTTPS=${PROXY_LISTEN_HTTPS:-443}
PROXY_LISTEN_HTTP=${PROXY_LISTEN_HTTP:-80}
PROXY_EXTRA_PORTS=${PROXY_EXTRA_PORTS:-}
PROXY_REALITY_SNI=${PROXY_REALITY_SNI:-}
PROXY_REALITY_BACKEND=${PROXY_REALITY_BACKEND:-127.0.0.1:12000}
PROXY_FALLBACK_BACKEND=${PROXY_FALLBACK_BACKEND:-127.0.0.1:11000}
EOF
  chmod 600 "$PROXY_CONFIG_FILE"
}

_proxy_load_config() {
  PROXY_ENGINE=""
  PROXY_MODE=""
  PROXY_PANEL_DOMAIN=""
  PROXY_SUB_DOMAIN=""
  PROXY_BACKEND_HOST="127.0.0.1"
  PROXY_BACKEND_PORT="8000"
  PROXY_LISTEN_HTTPS="443"
  PROXY_LISTEN_HTTP="80"
  PROXY_EXTRA_PORTS=""
  PROXY_REALITY_SNI=""
  PROXY_REALITY_BACKEND="127.0.0.1:12000"
  PROXY_FALLBACK_BACKEND="127.0.0.1:11000"
  if [[ -f "$PROXY_CONFIG_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$PROXY_CONFIG_FILE"
  fi
}

_proxy_valid_domain() {
  local d="$1"
  [[ "$d" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]
}

_proxy_valid_host() {
  # IPv4, localhost, or simple hostname/FQDN (no spaces / shell metacharacters)
  local h="$1"
  [[ -n "$h" ]] || return 1
  if declare -F is_ipv4 >/dev/null 2>&1 && is_ipv4 "$h"; then
    return 0
  fi
  [[ "$h" == "localhost" || "$h" == "::1" ]] && return 0
  [[ "$h" =~ ^[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$ ]]
}

_proxy_valid_hostport() {
  local hp="$1" host port
  [[ "$hp" == *:* ]] || return 1
  host="${hp%:*}"
  port="${hp##*:}"
  _proxy_valid_host "$host" && is_port "$port"
}

_proxy_find_ssl_pems() {
  # Populate PROXY_PEM_LIST with existing combined PEMs or build from SSL module / LE
  PROXY_PEM_LIST=()
  local f
  if [[ -d "$PROXY_HAPROXY_CERT_DIR" ]]; then
    while IFS= read -r f; do
      PROXY_PEM_LIST+=("$f")
    done < <(find "$PROXY_HAPROXY_CERT_DIR" -maxdepth 1 -type f -name '*.pem' 2>/dev/null | sort)
  fi
  if ((${#PROXY_PEM_LIST[@]} > 0)); then
    return 0
  fi
  return 1
}

_proxy_sync_pem_from_ssl() {
  # Build /etc/haproxy/certs/<domain>.pem from ToolBox SSL state or PasarGuard certs
  local domain="$1"
  [[ -n "$domain" ]] || return 1
  _proxy_ensure_state
  mkdir -p "$PROXY_HAPROXY_CERT_DIR"

  local cert="" key=""
  local ssl_live="${SECUREBOX_STATE_DIR}/ssl/live"
  local panel_dir="/var/lib/pasarguard/certs"

  if [[ -f "${ssl_live}/fullchain.cer" && -f "${ssl_live}/key.pem" ]]; then
    cert="${ssl_live}/fullchain.cer"
    key="${ssl_live}/key.pem"
  elif [[ -f "${panel_dir}/${domain}.cer" && -f "${panel_dir}/${domain}.cer.key" ]]; then
    cert="${panel_dir}/${domain}.cer"
    key="${panel_dir}/${domain}.cer.key"
  elif [[ -f "/etc/letsencrypt/live/${domain}/fullchain.pem" && -f "/etc/letsencrypt/live/${domain}/privkey.pem" ]]; then
    cert="/etc/letsencrypt/live/${domain}/fullchain.pem"
    key="/etc/letsencrypt/live/${domain}/privkey.pem"
  else
    return 1
  fi

  cat "$cert" "$key" >"${PROXY_HAPROXY_CERT_DIR}/${domain}.pem"
  chmod 600 "${PROXY_HAPROXY_CERT_DIR}/${domain}.pem"
  return 0
}

_proxy_ensure_certs_for_domains() {
  local -a domains=("$@")
  local d ok=0
  for d in "${domains[@]}"; do
    [[ -n "$d" ]] || continue
    if _proxy_sync_pem_from_ssl "$d"; then
      ui_success "HAProxy PEM ready: ${PROXY_HAPROXY_CERT_DIR}/${d}.pem"
      ok=1
    else
      ui_warn "No certificate found for ${d}"
    fi
  done
  if (( ok == 0 )); then
    ui_error "No usable certificates. Run SSL Certificates → Issue / Setup first."
    return 1
  fi
  return 0
}

_proxy_backup_file() {
  local src="$1"
  local dest="$2"
  [[ -f "$src" ]] || return 0
  [[ -f "$dest" ]] && return 0
  mkdir -p "$(dirname "$dest")"
  cp -a "$src" "$dest"
  ui_info "Backed up ${src} → ${dest}"
}

_proxy_print_panel_guide() {
  local backend_host="${1:-127.0.0.1}"
  local backend_port="${2:-8000}"
  ui_box_start "Panel settings (PasarGuard single-port docs)"
  ui_info "HAProxy terminates TLS. Panel must listen on local HTTP only."
  ui_kv "Panel Host" "$backend_host"
  ui_kv "Panel Port" "$backend_port"
  ui_info "Also set the same values in Panel UI → Settings → Panel"
  ui_info "Host ports for users: 443 / 80 / extra ports (HAProxy listens on them)"
  ui_box_end
}

# Align panel .env with official single-port guide: local HTTP, no Uvicorn TLS.
_proxy_prepare_panel_for_haproxy() {
  local backend_host="${1:-127.0.0.1}"
  local backend_port="${2:-8000}"
  local envf="/opt/pasarguard/.env"
  [[ -d /opt/pasarguard ]] || {
    ui_warn "/opt/pasarguard not found — set Panel Host/Port in the UI manually"
    return 0
  }
  if [[ ! -f "$envf" ]]; then
    touch "$envf"
    chmod 600 "$envf"
  elif declare -F backup_file >/dev/null 2>&1; then
    backup_file "$envf" || true
  fi

  if declare -F _ssl_env_comment_key >/dev/null 2>&1; then
    _ssl_env_comment_key "$envf" "UVICORN_SSL_CERTFILE"
    _ssl_env_comment_key "$envf" "UVICORN_SSL_KEYFILE"
    _ssl_env_comment_key "$envf" "UVICORN_UDS"
  fi
  if declare -F _ssl_env_upsert >/dev/null 2>&1; then
    _ssl_env_upsert "$envf" "UVICORN_HOST" "$backend_host" spaced
    _ssl_env_upsert "$envf" "UVICORN_PORT" "$backend_port" bare
  else
    ui_warn "SSL helpers missing — edit ${envf} manually"
    return 0
  fi
  ui_success "Panel .env prepared for HAProxy (local HTTP ${backend_host}:${backend_port}, SSL keys commented)"
  if declare -F _ssl_restart_compose >/dev/null 2>&1; then
    _ssl_restart_compose /opt/pasarguard "PasarGuard panel"
  fi
}

# --- HAProxy ---------------------------------------------------------------

_proxy_port_in_use() {
  local port="$1"
  if have_cmd ss; then
    ss -tlnH 2>/dev/null | awk '{print $4}' | grep -E "(:|\\.)${port}$" >/dev/null 2>&1
    return $?
  fi
  return 1
}

_proxy_warn_conflicts() {
  local other
  for other in caddy nginx; do
    if systemctl is-active --quiet "$other" 2>/dev/null; then
      ui_warn "${other} is active on this host — may conflict with HAProxy on :443"
      if have_tty && ui_confirm "Stop ${other} before continuing?" "Y"; then
        systemctl stop "$other" >/dev/null 2>&1 || true
        ui_info "Stopped ${other}"
      fi
    fi
  done
}

_proxy_install_haproxy() {
  if have_cmd haproxy; then
    ui_info "HAProxy already installed: $(haproxy -v 2>&1 | head -n1)"
    return 0
  fi
  ui_info "Installing HAProxy..."
  if ! apt_install_safe haproxy; then
    ui_error "Failed to install haproxy"
    return 1
  fi
  return 0
}

_proxy_write_haproxy_panel_cfg() {
  # Aligned with https://docs.pasarguard.org/en/learn/single-port/
  # listen front · mode http · Host ACL · deny default · PEM dir crt
  local panel_domain="$1"
  local sub_domain="$2"
  local backend_host="$3"
  local backend_port="$4"
  local listen_https="$5"
  local listen_http="$6"
  local extra_ssl_ports="$7"
  local extra_plain_ports="${8:-}"
  local p

  _proxy_backup_file "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_BAK"

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# MrClock ToolBox — PasarGuard panel single-port (HTTP mode)
# Based on official docs: https://docs.pasarguard.org/en/learn/single-port/
# Managed — regenerate from: mrclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode http
    log global
    option httplog
    option dontlognull
    timeout connect 5s
    timeout client  50s
    timeout server  50s
    maxconn 50000

# Official pattern: one listen block, several binds (SSL + plain HTTP).
# Port ${listen_http} stays plain HTTP (no forced redirect) so old HTTP
# subscription links keep working — same as PasarGuard docs.
listen front
    mode http
    option httplog
    log /dev/log local0
    bind :::${listen_https} v4v6 ssl crt ${PROXY_HAPROXY_CERT_DIR}/
    bind :::${listen_http} v4v6
EOF

  for p in $extra_ssl_ports; do
    [[ "$p" =~ ^[0-9]+$ ]] || continue
    (( p >= 1 && p <= 65535 )) || continue
    [[ "$p" == "$listen_https" || "$p" == "$listen_http" ]] && continue
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    bind :::${p} v4v6 ssl crt ${PROXY_HAPROXY_CERT_DIR}/
EOF
  done

  for p in $extra_plain_ports; do
    [[ "$p" =~ ^[0-9]+$ ]] || continue
    (( p >= 1 && p <= 65535 )) || continue
    [[ "$p" == "$listen_https" || "$p" == "$listen_http" ]] && continue
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    bind 0.0.0.0:${p}
EOF
  done

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    capture request header X-Forwarded-For len 15
    capture request header Host len 50
    log-format "%ci:%cp [%tr] %ft %b/%s %TR/%Tw/%Tc/%Tr/%Ta %ST %B %CC %CS %tsc %ac/%fc/%bc/%sc/%rc %sq/%bq %hr %hs %{+Q}r %U"
    acl host_panel hdr(host) -i ${panel_domain}
EOF
  if [[ -n "$sub_domain" && "$sub_domain" != "$panel_domain" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    acl host_sub hdr(host) -i ${sub_domain}
    use_backend panel if host_panel
    use_backend sub if host_sub
EOF
  else
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend panel if host_panel
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend deny_backend

backend panel
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    server srv1 ${backend_host}:${backend_port}

backend sub
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    acl is_sub path_beg /sub/
    http-request deny if !is_sub
    server srv1 ${backend_host}:${backend_port}

backend deny_backend
    mode http
    http-request deny deny_status 403
EOF
}

_proxy_write_haproxy_node_cfg() {
  # Aligned with official node TCP / REALITY example (send-proxy + inspect-delay)
  local listen_https="$1"
  local reality_sni="$2"
  local reality_backend="$3"
  local fallback_backend="$4"

  _proxy_backup_file "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_BAK"

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# MrClock ToolBox — PasarGuard node single-port (TCP / SNI mode)
# Based on official docs: https://docs.pasarguard.org/en/learn/single-port/
# Managed — regenerate from: mrclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode tcp
    log global
    option tcplog
    timeout connect 5s
    timeout client  1h
    timeout server  1h
    maxconn 50000

listen front_node
    mode tcp
    bind *:${listen_https}
    tcp-request inspect-delay 5s
    tcp-request content accept if { req_ssl_hello_type 1 }
EOF

  if [[ -n "$reality_sni" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend reality if { req.ssl_sni -m end ${reality_sni} }
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend fallback_node

backend fallback_node
    mode tcp
    server srv1 ${fallback_backend}

backend reality
    mode tcp
    server srv1 ${reality_backend} send-proxy
EOF
}

_proxy_haproxy_validate_and_start() {
  if ! haproxy -c -f "$PROXY_HAPROXY_CFG"; then
    ui_error "HAProxy config invalid — see above. Previous config kept at ${PROXY_HAPROXY_CFG_BAK}"
    if [[ -f "$PROXY_HAPROXY_CFG_BAK" ]]; then
      cp -a "$PROXY_HAPROXY_CFG_BAK" "$PROXY_HAPROXY_CFG"
      ui_warn "Restored previous haproxy.cfg"
    fi
    return 1
  fi
  systemctl enable haproxy >/dev/null 2>&1 || true
  if systemctl restart haproxy; then
    ui_success "HAProxy restarted"
  else
    ui_error "HAProxy failed to start — journalctl -u haproxy -n 40"
    return 1
  fi
  if systemctl is-active --quiet haproxy; then
    ui_success "HAProxy is active"
    return 0
  fi
  ui_error "HAProxy is not active"
  return 1
}

proxy_setup_haproxy() {
  ui_step "Setup HAProxy"
  if is_dry_run; then
    ui_info "[dry-run] Would install and configure HAProxy"
    return 0
  fi

  local mode_choice mode panel_domain sub_domain backend_host backend_port
  local listen_https listen_http extra_ports reality_sni reality_backend fallback_backend

  if ! ui_menu mode_choice "HAProxy mode" \
      "Panel — single-port HTTPS (recommended)" \
      "Node — TCP SNI / REALITY"; then
    ui_info "Back."
    return 0
  fi
  case "$mode_choice" in
    1) mode=panel ;;
    2) mode=node ;;
    *) return 0 ;;
  esac

  if [[ "$mode" == "panel" ]]; then
    while true; do
      ui_ask panel_domain "Panel domain" "${PROXY_PANEL_DOMAIN:-}"
      panel_domain="$(trim "${panel_domain,,}")"
      if _proxy_valid_domain "$panel_domain"; then break; fi
      ui_warn "Invalid domain."
    done
    ui_ask sub_domain "Subscription domain (optional, Enter to skip)" "${PROXY_SUB_DOMAIN:-}"
    sub_domain="$(trim "${sub_domain,,}")"
    if [[ -n "$sub_domain" ]] && ! _proxy_valid_domain "$sub_domain"; then
      ui_warn "Ignoring invalid sub domain."
      sub_domain=""
    fi
    while true; do
      ui_ask backend_host "Panel backend host" "127.0.0.1"
      backend_host="$(trim "$backend_host")"
      if _proxy_valid_host "$backend_host"; then break; fi
      ui_warn "Invalid host (use IPv4, localhost, or hostname)."
    done
    ui_ask_port backend_port "Panel backend port" "8000"
    ui_ask_port listen_https "HTTPS listen port" "443"
    ui_ask_port listen_http "HTTP listen port (plain, per docs — no redirect)" "80"
    ui_ask extra_ports "Extra HTTPS ports (optional, space-separated)" "8443"
    local extra_plain=""
    ui_ask extra_plain "Extra plain HTTP ports (optional, e.g. 9000)" "9000"

    if ! ui_confirm "Install HAProxy for ${panel_domain}${sub_domain:+ + $sub_domain}?" "Y"; then
      ui_warn "Cancelled."
      return 0
    fi

    _proxy_warn_conflicts
    if ! _proxy_install_haproxy; then return 1; fi

    local -a cert_domains=("$panel_domain")
    [[ -n "$sub_domain" ]] && cert_domains+=("$sub_domain")
    if ! _proxy_ensure_certs_for_domains "${cert_domains[@]}"; then
      ui_info "Tip: Main menu → SSL Certificates → Issue / Setup first"
      return 1
    fi

    _proxy_write_haproxy_panel_cfg \
      "$panel_domain" "$sub_domain" "$backend_host" "$backend_port" \
      "$listen_https" "$listen_http" "$extra_ports" "$extra_plain"

    PROXY_ENGINE=haproxy
    PROXY_MODE=panel
    PROXY_PANEL_DOMAIN="$panel_domain"
    PROXY_SUB_DOMAIN="$sub_domain"
    PROXY_BACKEND_HOST="$backend_host"
    PROXY_BACKEND_PORT="$backend_port"
    PROXY_LISTEN_HTTPS="$listen_https"
    PROXY_LISTEN_HTTP="$listen_http"
    PROXY_EXTRA_PORTS="$extra_ports"
    _proxy_save_config

    if ! _proxy_haproxy_validate_and_start; then return 1; fi

    ui_success "HAProxy panel mode ready (docs-aligned listen front)"
    _proxy_prepare_panel_for_haproxy "$backend_host" "$backend_port"
    _proxy_print_panel_guide "$backend_host" "$backend_port"
    ui_info "Firewall tip: ufw allow ${listen_https}/tcp ; ufw allow ${listen_http}/tcp"
    [[ -n "$extra_ports" ]] && ui_info "Also allow extra HTTPS: ${extra_ports}"
    [[ -n "$extra_plain" ]] && ui_info "Also allow plain ports: ${extra_plain}"
    return 0
  fi

  # Node mode
  ui_ask_port listen_https "Listen port" "443"
  ui_ask reality_sni "REALITY SNI suffix to match (e.g. reality.com)" ""
  reality_sni="$(trim "${reality_sni,,}")"
  if [[ -n "$reality_sni" ]] && ! _proxy_valid_domain "$reality_sni"; then
    ui_warn "Ignoring invalid REALITY SNI."
    reality_sni=""
  fi
  while true; do
    ui_ask reality_backend "REALITY backend host:port" "127.0.0.1:12000"
    reality_backend="$(trim "$reality_backend")"
    if _proxy_valid_hostport "$reality_backend"; then break; fi
    ui_warn "Invalid host:port."
  done
  while true; do
    ui_ask fallback_backend "Fallback / TLS backend host:port" "127.0.0.1:11000"
    fallback_backend="$(trim "$fallback_backend")"
    if _proxy_valid_hostport "$fallback_backend"; then break; fi
    ui_warn "Invalid host:port."
  done

  if ! ui_confirm "Install HAProxy node TCP mode on :${listen_https}?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi
  _proxy_warn_conflicts
  if ! _proxy_install_haproxy; then return 1; fi

  _proxy_write_haproxy_node_cfg "$listen_https" "$reality_sni" "$reality_backend" "$fallback_backend"

  PROXY_ENGINE=haproxy
  PROXY_MODE=node
  PROXY_LISTEN_HTTPS="$listen_https"
  PROXY_REALITY_SNI="$reality_sni"
  PROXY_REALITY_BACKEND="$reality_backend"
  PROXY_FALLBACK_BACKEND="$fallback_backend"
  _proxy_save_config

  if ! _proxy_haproxy_validate_and_start; then return 1; fi

  ui_success "HAProxy node mode ready on :${listen_https}"
  ui_box_start "Node inbound tips"
  ui_info "Point REALITY inbound listen to ${reality_backend} (127.0.0.1) with acceptProxyProtocol=true"
  ui_info "Point fallback/TLS inbound to ${fallback_backend}"
  ui_info "SNI match: *.${reality_sni:-<none>}"
  ui_box_end
  return 0
}


# --- Status / Remove -------------------------------------------------------

proxy_status() {
  ui_step "HAProxy — Status"
  _proxy_load_config
  ui_box_start "Saved configuration"
  ui_kv "Engine" "${PROXY_ENGINE:-(none)}"
  ui_kv "Mode" "${PROXY_MODE:-(none)}"
  ui_kv "Panel domain" "${PROXY_PANEL_DOMAIN:-(none)}"
  ui_kv "Sub domain" "${PROXY_SUB_DOMAIN:-(none)}"
  ui_kv "Backend" "${PROXY_BACKEND_HOST:-}:${PROXY_BACKEND_PORT:-}"
  ui_kv "HTTPS port" "${PROXY_LISTEN_HTTPS:-}"
  ui_kv "Config file" "$PROXY_CONFIG_FILE"
  ui_box_end

  if have_cmd haproxy || systemctl list-unit-files haproxy.service 2>/dev/null | grep -q haproxy; then
    if systemctl is-active --quiet haproxy 2>/dev/null; then
      ui_success "haproxy: active"
    else
      ui_info "haproxy: installed, not active"
    fi
  else
    ui_info "haproxy: not installed"
  fi

  if [[ -d "$PROXY_HAPROXY_CERT_DIR" ]]; then
    local n
    n="$(find "$PROXY_HAPROXY_CERT_DIR" -maxdepth 1 -type f -name '*.pem' 2>/dev/null | wc -l | tr -d ' ')"
    ui_kv "HAProxy PEMs" "${n} under ${PROXY_HAPROXY_CERT_DIR}"
  fi
}

proxy_remove() {
  ui_step "HAProxy — Remove"
  _proxy_load_config
  if ! ui_confirm "Stop HAProxy and restore previous config if backed up?" "N"; then
    ui_warn "Cancelled."
    return 0
  fi
  systemctl disable --now haproxy >/dev/null 2>&1 || true
  if [[ -f "$PROXY_HAPROXY_CFG_BAK" ]]; then
    cp -a "$PROXY_HAPROXY_CFG_BAK" "$PROXY_HAPROXY_CFG"
    ui_info "Restored ${PROXY_HAPROXY_CFG}"
  fi
  if [[ -f "$PROXY_CONFIG_FILE" ]]; then
    mv -f "$PROXY_CONFIG_FILE" "${PROXY_CONFIG_FILE}.removed.$(date +%Y%m%d%H%M%S)"
  fi
  ui_success "HAProxy stopped. Certificate PEM files were left in place."
}

proxy_status_remove_menu() {
  while true; do
    ui_clear
    ui_banner
    ui_menu_title "HAProxy — Status / Remove"
    printf '  %s 1)%s Status\n' "$C_ORANGE" "$C_RESET"
    printf '  %s 2)%s Remove / Stop\n' "$C_ORANGE" "$C_RESET"
    ui_menu_back_line
    local choice
    printf '%sSelect%s [0-2]: ' "$C_ORANGE" "$C_RESET"
    ui_read choice
    choice="$(trim "${choice:-}")"
    case "$choice" in
      1) ui_clear; proxy_status; ui_pause ;;
      2) ui_clear; proxy_remove; ui_pause ;;
      0|b|B|back|Back) return 0 ;;
      *) ui_warn "Invalid selection."; sleep 1 ;;
    esac
  done
}

