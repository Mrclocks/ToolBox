#!/usr/bin/env bash
# Module: Reverse proxy — HAProxy (primary), Caddy, Nginx
# Goal: simplest path to single-port / TLS termination for PasarGuard
# shellcheck shell=bash

PROXY_STATE_DIR="${PROXY_STATE_DIR:-${SECUREBOX_STATE_DIR}/proxy}"
PROXY_CONFIG_FILE="${PROXY_CONFIG_FILE:-${PROXY_STATE_DIR}/config.env}"
PROXY_HAPROXY_CERT_DIR="${PROXY_HAPROXY_CERT_DIR:-/etc/haproxy/certs}"
PROXY_HAPROXY_CFG="${PROXY_HAPROXY_CFG:-/etc/haproxy/haproxy.cfg}"
PROXY_HAPROXY_CFG_BAK="${PROXY_STATE_DIR}/haproxy.cfg.pre-mrclock"
PROXY_CADDYFILE="${PROXY_CADDYFILE:-/etc/caddy/Caddyfile}"
PROXY_CADDYFILE_BAK="${PROXY_STATE_DIR}/Caddyfile.pre-mrclock"
PROXY_NGINX_SITE="${PROXY_NGINX_SITE:-/etc/nginx/sites-available/mrclock-pasarguard}"
PROXY_NGINX_LINK="${PROXY_NGINX_LINK:-/etc/nginx/sites-enabled/mrclock-pasarguard}"

# --- helpers ---------------------------------------------------------------

_proxy_ensure_state() {
  mkdir -p "$PROXY_STATE_DIR" "$PROXY_HAPROXY_CERT_DIR"
  chmod 700 "$PROXY_STATE_DIR" 2>/dev/null || true
}

_proxy_save_config() {
  _proxy_ensure_state
  cat >"$PROXY_CONFIG_FILE" <<EOF
# Generated by MrClock ToolBox
PROXY_ENGINE=${PROXY_ENGINE:-}
PROXY_MODE=${PROXY_MODE:-}
PROXY_PANEL_DOMAIN=${PROXY_PANEL_DOMAIN:-}
PROXY_SUB_DOMAIN=${PROXY_SUB_DOMAIN:-}
PROXY_BACKEND_HOST=${PROXY_BACKEND_HOST:-127.0.0.1}
PROXY_BACKEND_PORT=${PROXY_BACKEND_PORT:-8000}
PROXY_LISTEN_HTTPS=${PROXY_LISTEN_HTTPS:-443}
PROXY_LISTEN_HTTP=${PROXY_LISTEN_HTTP:-80}
PROXY_EXTRA_PORTS=${PROXY_EXTRA_PORTS:-}
PROXY_REALITY_SNI=${PROXY_REALITY_SNI:-}
PROXY_REALITY_BACKEND=${PROXY_REALITY_BACKEND:-127.0.0.1:12000}
PROXY_FALLBACK_BACKEND=${PROXY_FALLBACK_BACKEND:-127.0.0.1:11000}
EOF
  chmod 600 "$PROXY_CONFIG_FILE"
}

_proxy_load_config() {
  PROXY_ENGINE=""
  PROXY_MODE=""
  PROXY_PANEL_DOMAIN=""
  PROXY_SUB_DOMAIN=""
  PROXY_BACKEND_HOST="127.0.0.1"
  PROXY_BACKEND_PORT="8000"
  PROXY_LISTEN_HTTPS="443"
  PROXY_LISTEN_HTTP="80"
  PROXY_EXTRA_PORTS=""
  PROXY_REALITY_SNI=""
  PROXY_REALITY_BACKEND="127.0.0.1:12000"
  PROXY_FALLBACK_BACKEND="127.0.0.1:11000"
  if [[ -f "$PROXY_CONFIG_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$PROXY_CONFIG_FILE"
  fi
}

_proxy_valid_domain() {
  local d="$1"
  [[ "$d" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]
}

_proxy_find_ssl_pems() {
  # Populate PROXY_PEM_LIST with existing combined PEMs or build from SSL module / LE
  PROXY_PEM_LIST=()
  local f
  if [[ -d "$PROXY_HAPROXY_CERT_DIR" ]]; then
    while IFS= read -r f; do
      PROXY_PEM_LIST+=("$f")
    done < <(find "$PROXY_HAPROXY_CERT_DIR" -maxdepth 1 -type f -name '*.pem' 2>/dev/null | sort)
  fi
  if ((${#PROXY_PEM_LIST[@]} > 0)); then
    return 0
  fi
  return 1
}

_proxy_sync_pem_from_ssl() {
  # Build /etc/haproxy/certs/<domain>.pem from ToolBox SSL state or PasarGuard certs
  local domain="$1"
  [[ -n "$domain" ]] || return 1
  _proxy_ensure_state
  mkdir -p "$PROXY_HAPROXY_CERT_DIR"

  local cert="" key=""
  local ssl_live="${SECUREBOX_STATE_DIR}/ssl/live"
  local panel_dir="/var/lib/pasarguard/certs"

  if [[ -f "${ssl_live}/fullchain.cer" && -f "${ssl_live}/key.pem" ]]; then
    cert="${ssl_live}/fullchain.cer"
    key="${ssl_live}/key.pem"
  elif [[ -f "${panel_dir}/${domain}.cer" && -f "${panel_dir}/${domain}.cer.key" ]]; then
    cert="${panel_dir}/${domain}.cer"
    key="${panel_dir}/${domain}.cer.key"
  elif [[ -f "/etc/letsencrypt/live/${domain}/fullchain.pem" && -f "/etc/letsencrypt/live/${domain}/privkey.pem" ]]; then
    cert="/etc/letsencrypt/live/${domain}/fullchain.pem"
    key="/etc/letsencrypt/live/${domain}/privkey.pem"
  else
    return 1
  fi

  cat "$cert" "$key" >"${PROXY_HAPROXY_CERT_DIR}/${domain}.pem"
  chmod 600 "${PROXY_HAPROXY_CERT_DIR}/${domain}.pem"
  return 0
}

_proxy_ensure_certs_for_domains() {
  local -a domains=("$@")
  local d ok=0
  for d in "${domains[@]}"; do
    [[ -n "$d" ]] || continue
    if _proxy_sync_pem_from_ssl "$d"; then
      ui_success "HAProxy PEM ready: ${PROXY_HAPROXY_CERT_DIR}/${d}.pem"
      ok=1
    else
      ui_warn "No certificate found for ${d}"
    fi
  done
  if (( ok == 0 )); then
    ui_error "No usable certificates. Run SSL Certificates → Issue / Setup first."
    return 1
  fi
  return 0
}

_proxy_backup_file() {
  local src="$1"
  local dest="$2"
  [[ -f "$src" ]] || return 0
  [[ -f "$dest" ]] && return 0
  mkdir -p "$(dirname "$dest")"
  cp -a "$src" "$dest"
  ui_info "Backed up ${src} → ${dest}"
}

_proxy_print_panel_guide() {
  local backend_host="${1:-127.0.0.1}"
  local backend_port="${2:-8000}"
  ui_box_start "Panel settings after reverse proxy"
  ui_info "HAProxy/Nginx terminate TLS. Panel should listen on HTTP locally (no UVICORN_SSL_*)."
  echo
  printf '   # /opt/pasarguard/.env\n'
  printf '   UVICORN_HOST = "%s"\n' "$backend_host"
  printf '   UVICORN_PORT = %s\n' "$backend_port"
  printf '   # Remove or comment out:\n'
  printf '   # UVICORN_SSL_CERTFILE = ...\n'
  printf '   # UVICORN_SSL_KEYFILE  = ...\n'
  echo
  ui_info "Panel UI → Settings → Panel: Host=${backend_host}  Port=${backend_port}"
  ui_info "Then: cd /opt/pasarguard && docker compose restart"
  ui_box_end
}

# --- HAProxy ---------------------------------------------------------------

_proxy_install_haproxy() {
  if have_cmd haproxy; then
    ui_info "HAProxy already installed: $(haproxy -v 2>&1 | head -n1)"
    return 0
  fi
  ui_info "Installing HAProxy..."
  if ! apt_install_safe haproxy; then
    ui_error "Failed to install haproxy"
    return 1
  fi
  return 0
}

_proxy_write_haproxy_panel_cfg() {
  local panel_domain="$1"
  local sub_domain="$2"
  local backend_host="$3"
  local backend_port="$4"
  local listen_https="$5"
  local listen_http="$6"
  local extra_ports="$7"
  local p

  _proxy_backup_file "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_BAK"

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# MrClock ToolBox — PasarGuard panel single-port (HTTP mode)
# Managed file — regenerate from: mrclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode http
    log global
    option httplog
    option dontlognull
    timeout connect 5s
    timeout client  50s
    timeout server  50s
    maxconn 50000

frontend http_redirect
    bind :::${listen_http} v4v6
    mode http
    redirect scheme https code 301 if !{ ssl_fc }

frontend front
    mode http
    option httplog
    bind :::${listen_https} v4v6 ssl crt ${PROXY_HAPROXY_CERT_DIR}/
EOF

  for p in $extra_ports; do
    [[ "$p" =~ ^[0-9]+$ ]] || continue
    (( p >= 1 && p <= 65535 )) || continue
    [[ "$p" == "$listen_https" || "$p" == "$listen_http" ]] && continue
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    bind :::${p} v4v6 ssl crt ${PROXY_HAPROXY_CERT_DIR}/
EOF
  done

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    acl host_panel hdr(host) -i ${panel_domain}
EOF
  if [[ -n "$sub_domain" && "$sub_domain" != "$panel_domain" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    acl host_sub hdr(host) -i ${sub_domain}
    use_backend panel if host_panel
    use_backend sub if host_sub
EOF
  else
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend panel if host_panel
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend deny_backend

backend panel
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    server srv1 ${backend_host}:${backend_port} check

backend sub
    mode http
    option forwardfor
    http-request set-header X-Forwarded-Proto https if { ssl_fc }
    acl is_sub path_beg /sub/
    http-request deny if !is_sub
    server srv1 ${backend_host}:${backend_port} check

backend deny_backend
    mode http
    http-request deny deny_status 403
EOF
}

_proxy_write_haproxy_node_cfg() {
  local listen_https="$1"
  local reality_sni="$2"
  local reality_backend="$3"
  local fallback_backend="$4"

  _proxy_backup_file "$PROXY_HAPROXY_CFG" "$PROXY_HAPROXY_CFG_BAK"

  cat >"$PROXY_HAPROXY_CFG" <<EOF
# MrClock ToolBox — PasarGuard node single-port (TCP / SNI mode)
# Managed file — regenerate from: mrclock → Reverse Proxy → HAProxy

global
    maxconn 50000
    log /dev/log local0
    user haproxy
    group haproxy
    daemon

defaults
    mode tcp
    log global
    option tcplog
    timeout connect 5s
    timeout client  1h
    timeout server  1h
    maxconn 50000

frontend front_node
    mode tcp
    bind :::${listen_https} v4v6
    tcp-request inspect-delay 5s
    tcp-request content accept if { req_ssl_hello_type 1 }
EOF

  if [[ -n "$reality_sni" ]]; then
    cat >>"$PROXY_HAPROXY_CFG" <<EOF
    use_backend reality if { req.ssl_sni -m end ${reality_sni} }
EOF
  fi

  cat >>"$PROXY_HAPROXY_CFG" <<EOF
    default_backend fallback_node

backend fallback_node
    mode tcp
    server srv1 ${fallback_backend}

backend reality
    mode tcp
    server srv1 ${reality_backend} send-proxy
EOF
}

_proxy_haproxy_validate_and_start() {
  if ! haproxy -c -f "$PROXY_HAPROXY_CFG"; then
    ui_error "HAProxy config invalid — see above. Previous config kept at ${PROXY_HAPROXY_CFG_BAK}"
    if [[ -f "$PROXY_HAPROXY_CFG_BAK" ]]; then
      cp -a "$PROXY_HAPROXY_CFG_BAK" "$PROXY_HAPROXY_CFG"
      ui_warn "Restored previous haproxy.cfg"
    fi
    return 1
  fi
  systemctl enable haproxy >/dev/null 2>&1 || true
  if systemctl restart haproxy; then
    ui_success "HAProxy restarted"
  else
    ui_error "HAProxy failed to start — journalctl -u haproxy -n 40"
    return 1
  fi
  if systemctl is-active --quiet haproxy; then
    ui_success "HAProxy is active"
    return 0
  fi
  ui_error "HAProxy is not active"
  return 1
}

proxy_setup_haproxy() {
  ui_step "Setup HAProxy"
  if is_dry_run; then
    ui_info "[dry-run] Would install and configure HAProxy"
    return 0
  fi

  local mode_choice mode panel_domain sub_domain backend_host backend_port
  local listen_https listen_http extra_ports reality_sni reality_backend fallback_backend

  ui_menu mode_choice "HAProxy mode" \
    "Panel — single-port HTTPS (recommended)" \
    "Node — TCP SNI / REALITY"
  case "$mode_choice" in
    1) mode=panel ;;
    2) mode=node ;;
  esac

  if [[ "$mode" == "panel" ]]; then
    while true; do
      ui_ask panel_domain "Panel domain" "${PROXY_PANEL_DOMAIN:-}"
      panel_domain="$(trim "${panel_domain,,}")"
      if _proxy_valid_domain "$panel_domain"; then break; fi
      ui_warn "Invalid domain."
    done
    ui_ask sub_domain "Subscription domain (optional, Enter to skip)" "${PROXY_SUB_DOMAIN:-}"
    sub_domain="$(trim "${sub_domain,,}")"
    if [[ -n "$sub_domain" ]] && ! _proxy_valid_domain "$sub_domain"; then
      ui_warn "Ignoring invalid sub domain."
      sub_domain=""
    fi
    ui_ask backend_host "Panel backend host" "127.0.0.1"
    ui_ask_port backend_port "Panel backend port" "8000"
    ui_ask_port listen_https "HTTPS listen port" "443"
    ui_ask_port listen_http "HTTP listen port (redirect)" "80"
    ui_ask extra_ports "Extra HTTPS ports (optional, space-separated)" "8443"

    if ! ui_confirm "Install HAProxy for ${panel_domain}${sub_domain:+ + $sub_domain}?" "Y"; then
      ui_warn "Cancelled."
      return 0
    fi

    if ! _proxy_install_haproxy; then return 1; fi

    local -a cert_domains=("$panel_domain")
    [[ -n "$sub_domain" ]] && cert_domains+=("$sub_domain")
    if ! _proxy_ensure_certs_for_domains "${cert_domains[@]}"; then
      ui_info "Tip: Main menu → SSL Certificates → Issue / Setup"
      return 1
    fi

    _proxy_write_haproxy_panel_cfg \
      "$panel_domain" "$sub_domain" "$backend_host" "$backend_port" \
      "$listen_https" "$listen_http" "$extra_ports"

    PROXY_ENGINE=haproxy
    PROXY_MODE=panel
    PROXY_PANEL_DOMAIN="$panel_domain"
    PROXY_SUB_DOMAIN="$sub_domain"
    PROXY_BACKEND_HOST="$backend_host"
    PROXY_BACKEND_PORT="$backend_port"
    PROXY_LISTEN_HTTPS="$listen_https"
    PROXY_LISTEN_HTTP="$listen_http"
    PROXY_EXTRA_PORTS="$extra_ports"
    _proxy_save_config

    if ! _proxy_haproxy_validate_and_start; then return 1; fi

    ui_success "HAProxy panel mode ready on :${listen_https}"
    _proxy_print_panel_guide "$backend_host" "$backend_port"
    ui_info "Open firewall if needed: ufw allow ${listen_https}/tcp && ufw allow ${listen_http}/tcp"
    return 0
  fi

  # Node mode
  ui_ask_port listen_https "Listen port" "443"
  ui_ask reality_sni "REALITY SNI suffix to match (e.g. reality.com)" ""
  reality_sni="$(trim "${reality_sni,,}")"
  ui_ask reality_backend "REALITY backend host:port" "127.0.0.1:12000"
  ui_ask fallback_backend "Fallback / TLS backend host:port" "127.0.0.1:11000"

  if ! ui_confirm "Install HAProxy node TCP mode on :${listen_https}?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi
  if ! _proxy_install_haproxy; then return 1; fi

  _proxy_write_haproxy_node_cfg "$listen_https" "$reality_sni" "$reality_backend" "$fallback_backend"

  PROXY_ENGINE=haproxy
  PROXY_MODE=node
  PROXY_LISTEN_HTTPS="$listen_https"
  PROXY_REALITY_SNI="$reality_sni"
  PROXY_REALITY_BACKEND="$reality_backend"
  PROXY_FALLBACK_BACKEND="$fallback_backend"
  _proxy_save_config

  if ! _proxy_haproxy_validate_and_start; then return 1; fi

  ui_success "HAProxy node mode ready on :${listen_https}"
  ui_box_start "Node inbound tips"
  ui_info "Point REALITY inbound listen to ${reality_backend} (127.0.0.1) with acceptProxyProtocol=true"
  ui_info "Point fallback/TLS inbound to ${fallback_backend}"
  ui_info "SNI match: *.${reality_sni:-<none>}"
  ui_box_end
  return 0
}

# --- Caddy -----------------------------------------------------------------

_proxy_install_caddy() {
  if have_cmd caddy; then
    ui_info "Caddy already installed: $(caddy version 2>/dev/null | head -n1)"
    return 0
  fi
  ui_info "Installing Caddy..."
  if ! apt_install_safe caddy; then
    ui_error "Failed to install caddy (apt). On older distros add the Caddy apt repo first."
    return 1
  fi
  return 0
}

proxy_setup_caddy() {
  ui_step "Setup Caddy"
  if is_dry_run; then
    ui_info "[dry-run] Would install Caddy with automatic HTTPS"
    return 0
  fi

  ui_warn "Caddy manages its own HTTPS (ACME). Do not also run ToolBox SSL Issue for the same domain."
  local domain backend_host backend_port
  while true; do
    ui_ask domain "Domain for panel" "${PROXY_PANEL_DOMAIN:-}"
    domain="$(trim "${domain,,}")"
    if _proxy_valid_domain "$domain"; then break; fi
    ui_warn "Invalid domain."
  done
  ui_ask backend_host "Backend host" "127.0.0.1"
  ui_ask_port backend_port "Backend port" "8000"

  if ! ui_confirm "Install Caddy for https://${domain} → ${backend_host}:${backend_port}?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi
  if ! _proxy_install_caddy; then return 1; fi

  _proxy_backup_file "$PROXY_CADDYFILE" "$PROXY_CADDYFILE_BAK"
  mkdir -p "$(dirname "$PROXY_CADDYFILE")"
  cat >"$PROXY_CADDYFILE" <<EOF
# MrClock ToolBox — Caddy reverse proxy for PasarGuard
${domain} {
	reverse_proxy ${backend_host}:${backend_port}
}
EOF

  if ! caddy validate --config "$PROXY_CADDYFILE" 2>/dev/null; then
    # Older caddy uses different validate flags
    ui_warn "caddy validate skipped or failed — starting anyway"
  fi

  systemctl enable caddy >/dev/null 2>&1 || true
  if ! systemctl restart caddy; then
    ui_error "Caddy failed to start — journalctl -u caddy -n 40"
    return 1
  fi

  PROXY_ENGINE=caddy
  PROXY_MODE=panel
  PROXY_PANEL_DOMAIN="$domain"
  PROXY_BACKEND_HOST="$backend_host"
  PROXY_BACKEND_PORT="$backend_port"
  _proxy_save_config

  ui_success "Caddy active for https://${domain}"
  _proxy_print_panel_guide "$backend_host" "$backend_port"
  return 0
}

# --- Nginx -----------------------------------------------------------------

_proxy_install_nginx() {
  if have_cmd nginx; then
    ui_info "Nginx already installed"
    return 0
  fi
  ui_info "Installing Nginx..."
  if ! apt_install_safe nginx; then
    ui_error "Failed to install nginx"
    return 1
  fi
  return 0
}

proxy_setup_nginx() {
  ui_step "Setup Nginx"
  if is_dry_run; then
    ui_info "[dry-run] Would install Nginx reverse proxy"
    return 0
  fi

  local domain backend_host backend_port cert key
  while true; do
    ui_ask domain "Panel domain" "${PROXY_PANEL_DOMAIN:-}"
    domain="$(trim "${domain,,}")"
    if _proxy_valid_domain "$domain"; then break; fi
    ui_warn "Invalid domain."
  done
  ui_ask backend_host "Backend host" "127.0.0.1"
  ui_ask_port backend_port "Backend port" "8000"

  # Prefer PasarGuard / ToolBox SSL paths
  cert="/var/lib/pasarguard/certs/${domain}.cer"
  key="/var/lib/pasarguard/certs/${domain}.cer.key"
  if [[ ! -f "$cert" || ! -f "$key" ]]; then
    if [[ -f "${SECUREBOX_STATE_DIR}/ssl/live/fullchain.cer" ]]; then
      cert="${SECUREBOX_STATE_DIR}/ssl/live/fullchain.cer"
      key="${SECUREBOX_STATE_DIR}/ssl/live/key.pem"
    elif [[ -f "/etc/letsencrypt/live/${domain}/fullchain.pem" ]]; then
      cert="/etc/letsencrypt/live/${domain}/fullchain.pem"
      key="/etc/letsencrypt/live/${domain}/privkey.pem"
    else
      ui_error "No certificate for ${domain}. Run SSL Certificates → Issue / Setup first."
      return 1
    fi
  fi

  if ! ui_confirm "Install Nginx for https://${domain} → ${backend_host}:${backend_port}?" "Y"; then
    ui_warn "Cancelled."
    return 0
  fi
  if ! _proxy_install_nginx; then return 1; fi

  mkdir -p /etc/nginx/sites-available /etc/nginx/sites-enabled
  cat >"$PROXY_NGINX_SITE" <<EOF
# MrClock ToolBox — Nginx reverse proxy for PasarGuard
server {
    listen 80;
    listen [::]:80;
    server_name ${domain};
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${domain};

    ssl_certificate     ${cert};
    ssl_certificate_key ${key};

    location / {
        proxy_pass http://${backend_host}:${backend_port};
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
    }
}
EOF

  ln -sfn "$PROXY_NGINX_SITE" "$PROXY_NGINX_LINK"
  # Avoid default site stealing :80/:443 when present
  if [[ -L /etc/nginx/sites-enabled/default ]]; then
    rm -f /etc/nginx/sites-enabled/default
    ui_info "Disabled nginx default site"
  fi

  if ! nginx -t; then
    ui_error "nginx -t failed"
    return 1
  fi
  systemctl enable nginx >/dev/null 2>&1 || true
  if ! systemctl restart nginx; then
    ui_error "Nginx failed to start"
    return 1
  fi

  PROXY_ENGINE=nginx
  PROXY_MODE=panel
  PROXY_PANEL_DOMAIN="$domain"
  PROXY_BACKEND_HOST="$backend_host"
  PROXY_BACKEND_PORT="$backend_port"
  _proxy_save_config

  ui_success "Nginx active for https://${domain}"
  _proxy_print_panel_guide "$backend_host" "$backend_port"
  return 0
}

# --- Status / Remove -------------------------------------------------------

proxy_status() {
  ui_step "Reverse Proxy — Status"
  _proxy_load_config
  ui_box_start "Saved configuration"
  ui_kv "Engine" "${PROXY_ENGINE:-(none)}"
  ui_kv "Mode" "${PROXY_MODE:-(none)}"
  ui_kv "Panel domain" "${PROXY_PANEL_DOMAIN:-(none)}"
  ui_kv "Sub domain" "${PROXY_SUB_DOMAIN:-(none)}"
  ui_kv "Backend" "${PROXY_BACKEND_HOST:-}:${PROXY_BACKEND_PORT:-}"
  ui_kv "HTTPS port" "${PROXY_LISTEN_HTTPS:-}"
  ui_kv "Config file" "$PROXY_CONFIG_FILE"
  ui_box_end

  local svc
  for svc in haproxy caddy nginx; do
    if have_cmd "$svc" || systemctl list-unit-files "${svc}.service" 2>/dev/null | grep -q "${svc}"; then
      if systemctl is-active --quiet "$svc" 2>/dev/null; then
        ui_success "${svc}: active"
      else
        ui_info "${svc}: installed, not active"
      fi
    fi
  done

  if [[ -d "$PROXY_HAPROXY_CERT_DIR" ]]; then
    local n
    n="$(find "$PROXY_HAPROXY_CERT_DIR" -maxdepth 1 -type f -name '*.pem' 2>/dev/null | wc -l | tr -d ' ')"
    ui_kv "HAProxy PEMs" "${n} under ${PROXY_HAPROXY_CERT_DIR}"
  fi
}

proxy_remove() {
  ui_step "Reverse Proxy — Remove"
  _proxy_load_config
  local engine="${PROXY_ENGINE:-}"
  if [[ -z "$engine" ]]; then
    ui_warn "No ToolBox proxy config saved."
    if ! ui_confirm "Stop common proxy services anyway (haproxy/caddy/nginx)?" "N"; then
      return 0
    fi
  fi

  if ! ui_confirm "Stop and disable ${engine:-proxy services}, restore backups if present?" "N"; then
    ui_warn "Cancelled."
    return 0
  fi

  case "$engine" in
    haproxy|"")
      systemctl disable --now haproxy >/dev/null 2>&1 || true
      if [[ -f "$PROXY_HAPROXY_CFG_BAK" ]]; then
        cp -a "$PROXY_HAPROXY_CFG_BAK" "$PROXY_HAPROXY_CFG"
        ui_info "Restored ${PROXY_HAPROXY_CFG}"
      fi
      ;;
  esac
  case "$engine" in
    caddy|"")
      systemctl disable --now caddy >/dev/null 2>&1 || true
      if [[ -f "$PROXY_CADDYFILE_BAK" ]]; then
        cp -a "$PROXY_CADDYFILE_BAK" "$PROXY_CADDYFILE"
        ui_info "Restored ${PROXY_CADDYFILE}"
      fi
      ;;
  esac
  case "$engine" in
    nginx|"")
      systemctl disable --now nginx >/dev/null 2>&1 || true
      rm -f "$PROXY_NGINX_LINK"
      ;;
  esac

  if [[ -f "$PROXY_CONFIG_FILE" ]]; then
    mv -f "$PROXY_CONFIG_FILE" "${PROXY_CONFIG_FILE}.removed.$(date +%Y%m%d%H%M%S)"
  fi
  ui_success "Proxy services stopped. Certificates were left in place."
}

proxy_status_remove_menu() {
  while true; do
    ui_clear
    ui_banner
    printf '%sStatus / Remove%s\n' "$C_BOLD$C_ORANGE" "$C_RESET"
    ui_line 56 '-'
    printf '  %s 1)%s Status\n' "$C_ORANGE" "$C_RESET"
    printf '  %s 2)%s Remove / Stop\n' "$C_ORANGE" "$C_RESET"
    printf '  %s 0)%s Back\n' "$C_YELLOW" "$C_RESET"
    ui_line 56 '-'
    local choice
    printf '%sSelect%s: ' "$C_ORANGE" "$C_RESET"
    ui_read choice
    choice="$(trim "${choice:-0}")"
    case "$choice" in
      1) ui_clear; proxy_status; ui_pause ;;
      2) ui_clear; proxy_remove; ui_pause ;;
      0|b|B) return 0 ;;
      *) ui_warn "Invalid selection."; sleep 1 ;;
    esac
  done
}

